STYLES = {
    "Block": dict(color="#1f77b4", linestyle="-",  marker="o"),
    "Attn":  dict(color="#d62728", linestyle="--", marker="^"),
    "MLP":   dict(color="#2ca02c", linestyle=":",  marker="s"),
}

ORDER = ["ViT", "DeiT", "DINOv2", "DINOv3", "SwinV2"]


def main():
    fig, axes = plt.subplots(1, 5, figsize=(15, 3.0), sharey=True)

    for ax, arch in zip(axes, ORDER):
        series = DATA[arch]
        n_layers = len(series["Block"])
        xs = range(n_layers)
        for name in ("Block", "Attn", "MLP"):
            ax.plot(xs, series[name], label=name, linewidth=1.2,
                    markersize=2.6, **STYLES[name])
        ax.set_title(arch, fontsize=11)
        ax.set_xlabel("Layer index", fontsize=9)
        ax.set_ylim(-0.15, 1.03)
        # Same grid style as the accuracy plots (visualize_benchmark_results.py)
        ax.grid(True, color="#d4af37", alpha=0.4, linewidth=1, linestyle=":")
        ax.tick_params(labelsize=8)
        step = 4 if n_layers <= 24 else 8
        ax.set_xticks(list(range(0, n_layers, step)) + [n_layers - 1])

    axes[0].set_ylabel("Cosine similarity", fontsize=10)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=3, fontsize=10,
               frameon=False, bbox_to_anchor=(0.5, 1.06))
    fig.tight_layout(rect=(0, 0, 1, 0.97))

    out_dir = Path("results/plots")
    out_dir.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_dir / "vision_similarities.pdf", bbox_inches="tight")
    fig.savefig(out_dir / "vision_similarities.png", bbox_inches="tight", dpi=300)
    print(f"✓ Saved: {out_dir}/vision_similarities.pdf and .png")


if __name__ == "__main__":
    main()
